const THEME_STATE_REGISTRY_BY_ID = Object.freeze(
  THEME_STATE_REGISTRY.reduce((acc, entry) => {
    acc[entry.id] = entry;
    return acc;
  }, {})
);

export function listThemeStateSurfaces({ themeId = null } = {}) {
  if (!themeId || themeId === '*') {
    return [...THEME_STATE_REGISTRY];
  }
  return THEME_STATE_REGISTRY.filter((entry) => (
    entry.themeId === '*'
    || entry.themeId === themeId
  ));
}

export function getThemeStateSurface(surfaceId) {
  if (typeof surfaceId !== 'string' || !surfaceId.trim()) {
    return null;
  }
  return THEME_STATE_REGISTRY_BY_ID[surfaceId.trim()] || null;
}
