function resolveSwimPreset(self, {
    manualControlActive,
    manualHasInput,
    manualBoost,
    manualBrake,
    manualTurnIntent,
    turnNeed,
    wallSense,
}) {
    const turnInput = Math.abs(manualTurnIntent || 0);
    const nearWall = (wallSense?.near || 0) > 0.92 && (wallSense?.approachSpeed || 0) > 0.0025;

    let next = 'cruise';
    if (manualBrake || nearWall) next = 'evade';
    else if (manualControlActive && !manualHasInput) next = 'idle';
    else if ((manualControlActive && manualBoost) || turnNeed > 0.58) next = 'burst';
    else if (turnNeed > 0.26 || turnInput > 0.24 || (wallSense?.near || 0) > 0.74) next = 'turn';

    // Kick-and-glide bout management for autonomous CPG cruising
    if (!manualControlActive) {
        if (next === 'turn' || next === 'evade' || next === 'burst') {
            self.cpgBoutMode = 'kick';
            self.cpgBoutTicks = 70;
        } else {
            if (self.cpgBoutMode === undefined) {
                self.cpgBoutMode = 'kick';
                self.cpgBoutTicks = 90 + Math.floor(Math.random() * 60);
            }
            self.cpgBoutTicks = Math.max(0, (self.cpgBoutTicks || 0) - 1);
            if (self.cpgBoutTicks <= 0) {
                if (self.cpgBoutMode === 'kick') {
                    self.cpgBoutMode = 'glide';
                    self.cpgBoutTicks = 50 + Math.floor(Math.random() * 50);
                } else {
                    self.cpgBoutMode = 'kick';
                    self.cpgBoutTicks = 80 + Math.floor(Math.random() * 60);
                }
            }
            if (self.cpgBoutMode === 'glide' && turnNeed < 0.22 && (wallSense?.near || 0) < 0.68) {
                next = 'glide';
            }
        }
    } else {
        self.cpgBoutMode = 'kick';
    }

    const prev = self.swimPresetState || next;
    if (!manualControlActive) {
        if (prev === 'turn' && next !== 'turn' && turnNeed > 0.2) next = 'turn';
        if (prev === 'idle' && next === 'cruise' && turnNeed < 0.18) next = 'idle';
        if (prev === 'evade' && next !== 'evade' && (wallSense?.near || 0) > 0.72) next = 'evade';
    }
    self.swimPresetState = next;
    return {
        state: next,
        preset: SWIM_STATE_PRESETS[next] || SWIM_STATE_PRESETS.cruise,
    };
}

export { SWIM_STATE_PRESETS, resolveSwimPreset };
