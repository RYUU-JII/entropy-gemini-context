import { createLazyBackgroundKernelActionMessageBindings } from './backgroundKernelLazyActionMessageBindings.js';
import { createBackgroundKernelMessageRouterBindings } from './backgroundKernelMessageRouterBindings.js';
import { createBackgroundKernelProfileMutationControlBindings } from './backgroundKernelProfileMutationControlBindings.js';
import { buildBackgroundKernelTrackingRuntimeSnapshot } from './backgroundKernelTrackingRuntimeSnapshot.js';

export function createBackgroundKernelMessageBindings({
  keyMaterialRepository,
  resumeVaultBootstrap,
  statsRuntimeService,
  statsCollector,
  runtimeSessionRepository,
  statsAnalysisQueryService,
  statsTrendQueryService,
  statsRepository,
  tabTimeTracker,
  settingsService, settingsCache, settingsPersistence, broadcastSettingsUpdate,
  bootstrapSnapshotRepository, runtimeLanguageRepository,
  settingsPropagationQaFixture,
  schedulePostCommitSettingsEffects, runtimeFlagRepository,
  getProtectionRuntimeSnapshot, refreshProtectionRuntimeSnapshot,
  interventionLedger,
  requestTabClosure,
  storageSupportBindings,
  cleanupBlockedHistory,
  previewBlockedHistory,
  previewBlockedBookmarks,
  exportBlockedBookmarksHtml,
  faviconService,
  bootPrewarmService,
  zenPairwiseGpService,
  tacticalLogger,
  cycleStateManager,
  markNudgeAborted, markNudgePresented, markNudgeEpisodeCompleted, markNudgeResolved,
  scheduleNudgeTerminalOutboxDrain,
  trackingProtectionService,
  gateInterstitialController,
  popupBlockFlow,
  clseRepository,
  prepareFeedFlowSnapshot,
  commitFeedFlowSnapshot,
  recordContentFlowStats,
  sendProtectionUpdate,
  contentScriptOrchestrator,
  contentRuntimeDiagnostics,
  contentProtectionSync,
  maybeTriggerProtectionNudge,
  sentinelProtocolTimeline,
  specialSessionRuntime,
  checkScheduleStatus, endScheduleOccurrence, runManualSessionMutation,
  progressionService,
  guidanceService,
  profileGenerationReadiness,
  feedTopologyPersistentCertificationService,
  getInitPromise, getDashboardBootReadinessPromise,
  getProfileGenerationBootSettlementPromise,
  readProfileMutationLifecycle,
  profileMutationRuntimeGate,
  workerRuntimeEventCapability,
  browserPort,
} = {}) {
  const profileMutationActionHandlers = createBackgroundKernelProfileMutationControlBindings({
    settingsPersistence,
    storageSupportBindings,
    readProfileMutationLifecycle,
    profileMutationRuntimeGate,
  });
  const handleActionMessage = createLazyBackgroundKernelActionMessageBindings({
    progressionService,
    statsRuntimeService,
    statsAnalysisQueryService,
    statsTrendQueryService,
    statsRepository,
    tabTimeTracker,
    settingsService, settingsCache, settingsPersistence, broadcastSettingsUpdate,
    schedulePostCommitSettingsEffects, runtimeFlagRepository,
    getProtectionRuntimeSnapshot, refreshProtectionRuntimeSnapshot,
    interventionLedger,
    requestTabClosure,
    storageSupportBindings,
    readProfileMutationLifecycle,
    cleanupBlockedHistory,
    previewBlockedHistory,
    previewBlockedBookmarks,
    exportBlockedBookmarksHtml,
    faviconService,
    bootPrewarmService,
    zenPairwiseGpService,
    tacticalLogger,
    cycleStateManager,
    markNudgeAborted, markNudgePresented, markNudgeEpisodeCompleted, markNudgeResolved,
    scheduleNudgeTerminalOutboxDrain,
    trackingProtectionService,
    gateInterstitialController,
    contentScriptOrchestrator,
    maybeTriggerProtectionNudge,
    sentinelProtocolTimeline,
    specialSessionRuntime,
    checkScheduleStatus, endScheduleOccurrence, runManualSessionMutation,
    browserPort,
  });

  const backgroundMessageRouter = createBackgroundKernelMessageRouterBindings({
    statsRuntimeService, statsCollector, runtimeSessionRepository,
    keyMaterialRepository,
    resumeVaultBootstrap,
    bootstrapSnapshotRepository, runtimeLanguageRepository,
    settingsPropagationQaFixture,
    profileMutationActionHandlers,
    handleActionMessage,
    popupBlockFlow,
    settingsService,
    settingsCache,
    bootPrewarmService,
    clseRepository,
    prepareFeedFlowSnapshot,
    commitFeedFlowSnapshot,
    recordContentFlowStats,
    sendProtectionUpdate,
    contentScriptOrchestrator,
    contentRuntimeDiagnostics,
    contentProtectionSync,
    progressionService,
    guidanceService,
    profileGenerationReadiness,
    feedTopologyPersistentCertificationService,
    getInitPromise, getDashboardBootReadinessPromise,
    getProfileGenerationBootSettlementPromise,
    readProfileMutationLifecycle,
    profileMutationRuntimeGate,
    gateInterstitialController,
    workerRuntimeEventCapability,
    browserPort,
    readConsumptionQaSnapshot: async (tabId) => {
      const now = Date.now();
      const session = await gateInterstitialController.readTabSession(tabId);
      const flow = await tabTimeTracker.getConsumptionFlowSnapshot({ now });
      const memory = tabTimeTracker.getConsumptionMemorySnapshot({ now });
      const entryApproval = await trackingProtectionService.getGateEntryApproval();
      return { now, flow, memory, session, entryApproval };
    },
    releaseGateEntryApprovalForQa: trackingProtectionService.releaseGateEntryApprovalForQa,
    maybeTriggerProtectionNudge,
    requestTabClosure,
    getTrackingRuntimeState: () => buildBackgroundKernelTrackingRuntimeSnapshot({
      statsRuntimeService,
      tabTimeTracker,
    }),
  });

  return {
    combinedMessageHandler: backgroundMessageRouter.handleMessage,
    handleBuildCapabilityActionClicked:
      backgroundMessageRouter.handleBuildCapabilityActionClicked,
  };
}
