import { createBackgroundKernelTrackingBrowserBindings } from './backgroundKernelTrackingBrowserBindings.js';
import { createBackgroundKernelTrackingStatsBindings } from './backgroundKernelTrackingStatsBindings.js';

export function createBackgroundKernelTrackingRuntimeBindings({
  tabTimeTracker,
  statsRuntimeService,
  checkScheduleStatus,
  checkGlobalCapStatus,
  trackingProtectionService,
  frictionBootstrapCoordinator,
  syncManagedContentScripts,
  maybeTriggerProtectionNudge,
  flushTacticalLogsWrapper,
  getInitPromise,
  runProfileMutationAdmittedTask,
  captureProfileMutationRuntimeAdmission,
  runCapturedProfileMutationRuntimeTask,
  runNudgePendingSweep,
  clearNudgeWindowBlurTimer,
  cycleStateManager,
  backgroundBehaviorPolicy,
  recordCLSEShortDwell,
  faviconService,
  sendProtectionUpdate,
  handleWindowBlurNudgeAbort,
  maybeDeleteHistoryForUrl,
  cleanupRecentBlockedHistory,
  runMemoryPurgeArtifactCleanup,
  sweepStaleTabs,
  nudgeWindowBlurController,
  protectionDispatcher,
  gateInterstitialController,
  protectionRuntimeStateCoordinator,
  observeGateSitePresence,
  contentScriptOrchestrator,
  waitForSettingsPropagationIdle,
  tacticalLogger,
  browserPort,
  runtimeSessionRepository,
  statsRuntimeHealthLedger,
  contentProtectionSync,
  runCLSEHeartbeat,
} = {}) {
  const { statsTickRuntimeService } = createBackgroundKernelTrackingStatsBindings({
    tabTimeTracker,
    statsRuntimeService,
  });

  const trackingBrowserBindings = createBackgroundKernelTrackingBrowserBindings({
    tabTimeTracker,
    statsTickRuntimeService,
    statsRuntimeService,
    checkScheduleStatus,
    checkGlobalCapStatus,
    trackingProtectionService,
    frictionBootstrapCoordinator,
    syncManagedContentScripts,
    maybeTriggerProtectionNudge,
    flushTacticalLogsWrapper,
    getInitPromise,
    runProfileMutationAdmittedTask,
    captureProfileMutationRuntimeAdmission,
    runCapturedProfileMutationRuntimeTask,
    runNudgePendingSweep,
    clearNudgeWindowBlurTimer,
    cycleStateManager,
    backgroundBehaviorPolicy,
    recordCLSEShortDwell,
    faviconService,
    sendProtectionUpdate,
    handleWindowBlurNudgeAbort,
    maybeDeleteHistoryForUrl,
    cleanupRecentBlockedHistory,
    runMemoryPurgeArtifactCleanup,
    sweepStaleTabs,
    nudgeWindowBlurController,
    protectionDispatcher,
    gateInterstitialController,
    protectionRuntimeStateCoordinator,
    observeGateSitePresence,
    contentScriptOrchestrator,
    waitForSettingsPropagationIdle,
    tacticalLogger,
    browserPort,
    sessionStore: runtimeSessionRepository,
    statsRuntimeHealthLedger,
    contentProtectionSync,
    runCLSEHeartbeat,
  });

  return {
    statsTickRuntimeService,
    ...trackingBrowserBindings,
  };
}
