import {
  deleteCLSEData,
  resetCLSEData,
} from '../../../../domains/behavior/CLSEServiceClient.js';
import { MAX_DAYS_STORED } from './backgroundKernelRuntimeConfig.js';
import { createBackgroundMaintenanceCoordinator } from './support/BackgroundMaintenanceCoordinator.js';
import { GatePruningPresentationStore } from '../../../../platform/storage/presentation/GatePruningPresentationStore.js';
import { clearFurinDailyReceiptForProfileReset } from '../../../../domains/nudge/runtime/session/furinDailyPolicy.js';

export function createBackgroundKernelStorageMaintenanceBindings({
  workerRuntimeEventCapability,
  statsRuntimeService,
  statsRepository,
  eventLogRepository,
  tabTimeTracker,
  faviconRepository,
  statsFeaturePackRepository,
  interventionEffectRepository,
  settingsDocumentRepository,
  modelStateRepository,
  zenArtifactRepository,
  keyMaterialRepository,
  cycleStateManager,
  runtimeSessionRepository,
  profileMutationCoordinator,
  settingsService,
  checkGlobalCapStatus,
  bootPrewarmService,
  settingsPersistence,
  statsRetentionJob,
  frictionBootstrapCoordinator,
  progressionService,
  guidanceService,
  createZenProfileGenerationState,
} = {}) {
  return createBackgroundMaintenanceCoordinator({
    workerRuntimeEventCapability,
    clearGatePruningPresentation: () => new GatePruningPresentationStore().clear(),
    clearFurinDailyReceiptForProfileReset,
    clearGuidanceForProfileReset: guidanceService.clearForProfileReset,
    statsRepository,
    eventLogRepository,
    deleteCLSEData,
    resetStatsState: statsRuntimeService.resetStatsState,
    runStatsReset: statsRuntimeService.runStatsReset,
    runTerminalStatsReset: statsRuntimeService.runTerminalProfileMutationReset,
    runTerminalTrackingReset: tabTimeTracker.runTerminalProfileMutationReset,
    TabTimeTracker: tabTimeTracker,
    loadStatsCache: statsRuntimeService.loadStatsCache,
    faviconRepository,
    statsFeaturePackRepository,
    interventionEffectRepository,
    settingsDocumentRepository,
    modelStateRepository,
    zenArtifactRepository,
    keyMaterialRepository,
    cycleStateManager,
    runtimeSessionRepository,
    profileMutationCoordinator,
    resetCLSEData,
    settingsService,
    checkGlobalCapStatus,
    invalidateBootPrewarmSnapshot: (reason) => bootPrewarmService.invalidate(reason),
    clearBootstrapSnapshots: (reason) => frictionBootstrapCoordinator.clearAll(reason),
    settingsPersistence,
    statsRetentionJob,
    maxDaysStored: MAX_DAYS_STORED,
    progressionService,
    createZenProfileGenerationState,
  });
}
