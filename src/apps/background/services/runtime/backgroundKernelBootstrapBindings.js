import { createBackgroundBootstrapCoordinator } from './BackgroundBootstrapCoordinator.js';
import { createBackgroundKernelBrowserEventBindings } from './backgroundKernelBrowserEventBindings.js';
import { MAX_DAYS_STORED } from './backgroundKernelRuntimeConfig.js';

export function createBackgroundKernelBootstrapBindings({
  keyMaterialRepository,
  statsRetentionJob,
  statsRuntimeService,
  initializeClseLabs,
  rolloverLifecycle,
  settingsService,
  initializeArtifactDisclosure,
  bootPrewarmService,
  reconcileNudgeDebtSession,
  runNudgePendingSweep,
  popupBlockFlow,
  reconcileHistoryCleanupOnActivation,
  reconcileHistoryCleanupAfterPermissionAdded,
  reconcileStartupContentScripts,
  invalidateContentPermissions,
  checkGlobalCapStatus,
  syncBlockedBookmarks,
  restoreSettingsPropagation,
  drainNudgeTerminalOutbox,
  setupIdleDetection,
  idleDetector,
  tabTimeTracker,
  cycleStateManager,
  faviconService,
  handleAlarm,
  handleTabActivated,
  handleTabCreated,
  handleWindowFocusChanged,
  handleTabUpdated,
  handleTabRemoved,
  handleTabReplaced,
  handleWebNavigationCommitted,
  handleWebNavigationHistoryStateUpdated,
  handleHistoryVisited,
  handleBuildCapabilityActionClicked,
  combinedMessageHandler,
  notificationService,
  clearNudgeWindowBlurTimer,
  flushTacticalLogsWrapper,
  eventLogRepository,
  profileResetLifecycleRepository,
  profileMutationRuntimeGate,
  initializeZenProfileGeneration,
  serviceWorkerWakeTelemetry,
  browserPort,
  tabManagement,
} = {}) {
  let bootstrapCoordinator;
  const browserEventBindings = createBackgroundKernelBrowserEventBindings({
    tabManagement,
    waitForFullInit: options => bootstrapCoordinator.waitForFullInit(options),
  });

  bootstrapCoordinator = createBackgroundBootstrapCoordinator({
    prepareSecurityVault: keyMaterialRepository.ensureLocalVault.bind(keyMaterialRepository),
    readSecurityVaultStatus: keyMaterialRepository.getVaultStatus.bind(keyMaterialRepository),
    statsRetentionJob,
    maxDaysStored: MAX_DAYS_STORED,
    loadStatsCache: statsRuntimeService.loadStatsCache,
    initStatsRuntimeHealth: statsRuntimeService.initStatsRuntimeHealth,
    initializeClseLabs,
    setRolloverLifecycle: statsRuntimeService.setRolloverLifecycle,
    rolloverLifecycle,
    settingsService,
    initializeArtifactDisclosure,
    bootPrewarmService,
    reconcileNudgeDebtSession,
    runNudgePendingSweep,
    popupBlockFlow,
    reconcileHistoryCleanupOnActivation,
    reconcileHistoryCleanupAfterPermissionAdded,
    reconcileStartupContentScripts,
    invalidateContentPermissions,
    checkGlobalCapStatus,
    syncBlockedBookmarks,
    restoreSettingsPropagation,
    drainNudgeTerminalOutbox,
    setupIdleDetection,
    idleDetector,
    TabTimeTracker: tabTimeTracker,
    cycleStateManager,
    faviconService,
    handleAlarm,
    handleTabActivated,
    handleTabCreated,
    handleWindowFocusChanged,
    handleTabUpdated,
    handleTabRemoved,
    handleTabReplaced,
    handleWebNavigationCommitted,
    handleWebNavigationHistoryStateUpdated,
    handleHistoryVisited,
    handleBuildCapabilityActionClicked,
    combinedMessageHandler,
    notificationService,
    clearNudgeWindowBlurTimer,
    runStatsMutationBatch: statsRuntimeService.runStatsMutationBatch,
    flushTacticalLogsWrapper,
    eventLogStore: eventLogRepository,
    waitForProfileMutationAdmission: (
      profileResetLifecycleRepository.waitForWriteAdmission.bind(
        profileResetLifecycleRepository,
      )
    ),
    initializeZenProfileGeneration,
    serviceWorkerWakeTelemetry,
    profileMutationRuntimeGate,
    readLastFocusedWindow: browserEventBindings.readLastFocusedWindow,
    registerBrowserListeners: browserEventBindings.registerBrowserListeners,
    windowIdNone: browserEventBindings.windowIdNone,
    browserPort,
  });
  return bootstrapCoordinator;
}
