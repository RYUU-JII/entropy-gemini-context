function createPolicies(actions, sender) {
  return Object.fromEntries(actions.map((action) => [action, createPolicy(sender)]));
}

export const ACTION_SENDER_POLICY = Object.freeze({
  ...createPolicies(EXTENSION_PAGE_ONLY_ACTIONS, ACTION_SENDER_SCOPE.EXTENSION_PAGE),
  ...createPolicies(TRUSTED_EXTENSION_SENDER_ACTIONS, ACTION_SENDER_SCOPE.TRUSTED_EXTENSION_SENDER),
  ...createPolicies(TRUSTED_EXTENSION_TAB_ACTIONS, ACTION_SENDER_SCOPE.TRUSTED_EXTENSION_TAB),
  ...createPolicies(PRIVILEGED_SETTINGS_FLOW_ACTIONS, ACTION_SENDER_SCOPE.PRIVILEGED_SETTINGS_FLOW),
});

function resolvePolicyForAction(action) {
  return ACTION_SENDER_POLICY[action] || null;
}

function isSenderAllowedByPolicy(sender, policy) {
  if (policy.sender === ACTION_SENDER_SCOPE.EXTENSION_PAGE) {
    return isTrustedExtensionPageSender(sender);
  }
  if (policy.sender === ACTION_SENDER_SCOPE.PRIVILEGED_SETTINGS_FLOW) {
    return isPrivilegedSettingsFlowSender(sender);
  }
  if (policy.sender === ACTION_SENDER_SCOPE.TRUSTED_EXTENSION_TAB) {
    return isTrustedExtensionTabSender(sender);
  }
  if (policy.sender === ACTION_SENDER_SCOPE.TRUSTED_EXTENSION_SENDER) {
    return isTrustedExtensionSender(sender);
  }
  return false;
}

function authorizeActionSender(action, sender) {
  const policy = resolvePolicyForAction(action);
  if (!policy) {
    return { authorized: false, error: 'UNREGISTERED_RUNTIME_ACTION' };
  }
  if (!isSenderAllowedByPolicy(sender, policy)) {
    return { authorized: false, error: 'UNAUTHORIZED_RUNTIME_SENDER' };
  }
  return { authorized: true, error: null };
}

export function createActionSenderPolicy() {
  return {
    authorizeActionSender,
  };
}
