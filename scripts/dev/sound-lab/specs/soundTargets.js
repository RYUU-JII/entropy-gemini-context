export function getSoundTargetSpec(id) {
  return SOUND_TARGET_SPECS.find((spec) => spec.id === id) || null;
}

export function getSoundTargetsByTheme(theme) {
  return SOUND_TARGET_SPECS.filter((spec) => spec.theme === theme);
}

export function getSoundTargetsByScope(scope) {
  return SOUND_TARGET_SPECS.filter((spec) => spec.scope === scope);
}

export function getSoundTargetsByArtifact(theme, artifact) {
  return SOUND_TARGET_SPECS.filter((spec) => spec.theme === theme && spec.artifact === artifact);
}
